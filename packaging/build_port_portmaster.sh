# Assemble the PortMaster package: the directory PortMaster-New's
# ports/olduvai/ holds, and what its build_release.py zips.  Builds no binary
# (build_knulli_release.sh does: the same aarch64 / armhf builds) and ships
# NO GAME CONTENT: game/, mt32-roms/ and soundfonts/ are empty, the player
# copies their own files in.  Refuses to write inside the repo.
#
#   --binary-aarch64 P   the aarch64 binary                      (required)
#   --binary-armhf P     the armhf binary                        (optional)
#   --porter NAME        port.json's porter            (default: the author)
#   --out O              the package directory
#   --release-zip F      also write the zip PortMaster installs (autoinstall):
#                        Olduvai.sh and olduvai/ only, the store files inside
#                        olduvai/ where its installer reads them
#
# Every per-device fact comes from PortMaster at run time, never from this
# script: control.txt and the firmware module (mod_${CFW_NAME}.txt) set up
# the environment, device_info.txt gives the panel, which picks the default
# profile.  The KNULLI launchers (build_port_knulli.sh) stay beside this one
# for the owner's devices.
set -euo pipefail

BIN_AARCH64="" BIN_ARMHF="" OUT="" RELEASE_ZIP=""
PORTER="Krzysztof Sokołowski"
while [ $# -gt 0 ]; do
    case "$1" in
        --binary-aarch64) BIN_AARCH64="$2"; shift 2 ;;
        --binary-armhf)   BIN_ARMHF="$2"; shift 2 ;;
        --porter)         PORTER="$2"; shift 2 ;;
        --out)            OUT="$2"; shift 2 ;;
        --release-zip)    RELEASE_ZIP="$2"; shift 2 ;;
        -h|--help)
            sed -n '4,22p' "$0" | sed 's/^# \{0,1\}//'
            exit 0 ;;
        *) echo "build_port_portmaster: unknown option '$1'" >&2; exit 2 ;;
    esac
done
if [ -z "$BIN_AARCH64" ] || [ -z "$OUT" ]; then
    echo "build_port_portmaster: --binary-aarch64 and --out are required" >&2
    exit 2
fi

REPO_ROOT=$(cd "$(dirname "$0")/.." && pwd -P)
# shellcheck source=packaging/port_common.sh
. "${REPO_ROOT}/packaging/port_common.sh"
OUT_ABS=$(port_out_dir build_port_portmaster "$OUT") || exit 1
PORT="${OUT_ABS}/olduvai"
mkdir -p "$PORT"

# ── one binary per architecture (FluidSynth and libmt32emu compiled in) ─────
ARCHES=()
add_arch() {   # <arch> <binary>
    [ -n "$2" ] || return 0
    cp -L "$2" "${PORT}/olduvai.$1"
    chmod +x "${PORT}/olduvai.$1"
    ARCHES+=("$1")
}
add_arch aarch64 "$BIN_AARCH64"
add_arch armhf "$BIN_ARMHF"

port_copy_fonts "$PORT"
port_copy_licenses "$PORT"
# PortMaster keeps every licence under licenses/, ours included.
cp "${PORT}/LICENSE.txt" "${PORT}/licenses/LICENSE"
port_put_files_notes "$PORT" README.txt game mt32-roms soundfonts

# ── gptokeyb: every button unassigned ───────────────────────────────────────
# Olduvai reads the pad through SDL itself (menus, remapping, the Select-held
# shortcuts); gptokeyb runs only for PortMaster's Start+Select kill switch.
{
    echo "# Gameplay input is Olduvai's own (SDL game controller); gptokeyb"
    echo "# runs for PortMaster's Start+Select kill switch only."
    for k in back start guide a b x y l1 l2 l3 r1 r2 r3 up down left right \
             left_analog_up left_analog_down left_analog_left left_analog_right \
             right_analog_up right_analog_down right_analog_left \
             right_analog_right a_hk b_hk x_hk y_hk l1_hk l2_hk r1_hk r2_hk; do
        printf '%s = \\"\n' "$k"
    done
} > "${PORT}/olduvai.gptk"

# ── the launcher ────────────────────────────────────────────────────────────
cat > "${OUT_ABS}/Olduvai.sh" <<'LAUNCH'
#!/bin/bash
# Olduvai — PortMaster launcher.  Generated by packaging/build_port_portmaster.sh.

XDG_DATA_HOME=${XDG_DATA_HOME:-$HOME/.local/share}

if [ -d "/opt/system/Tools/PortMaster/" ]; then
  controlfolder="/opt/system/Tools/PortMaster"
elif [ -d "/opt/tools/PortMaster/" ]; then
  controlfolder="/opt/tools/PortMaster"
elif [ -d "$XDG_DATA_HOME/PortMaster/" ]; then
  controlfolder="$XDG_DATA_HOME/PortMaster"
else
  controlfolder="/roms/ports/PortMaster"
fi

source $controlfolder/control.txt
source $controlfolder/device_info.txt

# One binary per architecture, each native: never the 32-bit userland.
export PORT_32BIT="N"
[ -f "${controlfolder}/mod_${CFW_NAME}.txt" ] && source "${controlfolder}/mod_${CFW_NAME}.txt"

get_controls

GAMEDIR="/$directory/ports/olduvai"
cd "$GAMEDIR" || exit 1

> "$GAMEDIR/log.txt" && exec > >(tee "$GAMEDIR/log.txt") 2>&1

$ESUDO chmod 666 /dev/tty1
$ESUDO chmod 666 /dev/uinput

# Player state lives in the port: settings and saves (XDG_CONFIG_HOME), F5
# bug reports and the log.  An update replaces the build and never these.
export XDG_CONFIG_HOME="$GAMEDIR/conf"
export OLDUVAI_BUG_DIR="$GAMEDIR/bug_reports"
export SDL_GAMECONTROLLERCONFIG="$sdl_controllerconfig"

# The starting style, from the panel PortMaster reports: the largest scale whose
# frame fits its height, a step every 200 lines.  800 lines and up start
# Enhanced at x4 (a 1280x800 panel is exactly 4x), 600 and up at x3 (the
# Powkiddy A12's 1024x600), 400 and up at x2, a 4:3 panel filling its screen;
# anything shorter Classic.  A DEFAULT below the player's play.json, so a choice
# made under Options -> Style sticks.
W=${DISPLAY_WIDTH:-0}
H=${DISPLAY_HEIGHT:-0}
if [ "$H" -ge 800 ]; then
  PROFILE="hd-handheld-x4"
elif [ "$H" -ge 600 ]; then
  PROFILE="hd-handheld"
elif [ "$H" -ge 400 ] && [ $((W * 3)) -eq $((H * 4)) ]; then
  PROFILE="hd-handheld-43"
elif [ "$H" -ge 400 ]; then
  PROFILE="hd-handheld-x2"
else
  PROFILE="dos-handheld"
fi

# Optional local overrides (debug env vars): never shipped.
[ -f ./olduvai.env ] && . ./olduvai.env

set -- --game-dir ./game --rom-dir ./mt32-roms --default-profile "$PROFILE"
# The engine does not search beside itself for a SoundFont: hand one over.
for sf in ./soundfonts/*.sf2 ./soundfonts/*.sf3; do
  if [ -f "$sf" ]; then set -- "$@" --soundfont "$sf"; break; fi
done

# An install can carry a gptokeyb of the wrong architecture (an aarch64 one on
# an armhf A12): take the helper built for this device when PortMaster has it.
[ -x "$controlfolder/gptokeyb.${DEVICE_ARCH}" ] && \
  GPTOKEYB="$ESUDO $controlfolder/gptokeyb.${DEVICE_ARCH} $ESUDOKILL"
$GPTOKEYB "olduvai.${DEVICE_ARCH}" -c "$GAMEDIR/olduvai.gptk" &
pm_platform_helper "$GAMEDIR/olduvai.${DEVICE_ARCH}" >/dev/null
./olduvai.${DEVICE_ARCH} "$@"

pm_finish
LAUNCH
chmod +x "${OUT_ABS}/Olduvai.sh"

# ── the player's README, inside the port (PUT-FILES-HERE points here) ──────
cat > "${PORT}/README.txt" <<README
Olduvai (PortMaster)
====================

Olduvai is a native recreation of the ENGINE of Prehistorik (1991).  It ships no
game content and reads your own game files.  Get the game from GOG.com
("Prehistorik 1+2") or use your original DOS copy.


game  --  WHERE THE GAME FILES GO (the only step you must do)
-------------------------------------------------------------
$(port_readme_game_files ports/olduvai/game/)


mt32-roms / soundfonts  --  MUSIC
---------------------------------
$(port_readme_music ports/olduvai)


IF IT DOES NOT START
--------------------
Read  ports/olduvai/log.txt .  Its first line names the build; quote it in a
bug report.  A missing game file names the folder searched and the files wanted.


LICENCE
-------
Olduvai is free software, GPL-3.0-or-later (LICENSE.txt).  Third-party
components and their licences are in licenses/ and fonts/.  Source code:
https://github.com/ksokolowski/olduvai
README

# ── the store listing: screenshot, metadata, README.md ──────────────────────
# One curated still (assets/screenshots/README.md allows a port's store
# listing), 4:3 with the bars a 4:3 handheld shows.
cp "${REPO_ROOT}/assets/screenshots/classic-l1-4x3.png" "${OUT_ABS}/screenshot.png"
cp "${OUT_ABS}/screenshot.png" "${PORT}/screenshot.png"

DESC="The 1991 caveman platformer on Olduvai, a native recreation of its engine. Classic DOS plays it exactly as it was; Enhanced HD adds smooth motion, widescreen margins and sharp upscaled graphics. Switch any time under Options - Style."
INST="Needs your own copy of the game (GOG's Prehistorik 1+2, or the DOS original): copy FILESA.CUR, FILESB.CUR, FILESA.VGA, FILESB.VGA and HISTORIK.EXE (or GOG's PREH.SQZ) into ports/olduvai/game/. Roland MT-32 / CM-32L ROMs (ports/olduvai/mt32-roms/) or a SoundFont (ports/olduvai/soundfonts/) are optional; without them the AdLib / Sound Blaster sound plays."
ARCH_JSON=$(printf '"%s", ' "${ARCHES[@]}"); ARCH_JSON="[${ARCH_JSON%, }]"
python3 - "$OUT_ABS/port.json" "$PORTER" "$DESC" "$INST" "$ARCH_JSON" <<'PY'
import json, sys
path, porter, desc, inst, arch = sys.argv[1:]
port = {
    "version": 4,
    "name": "olduvai.zip",
    "items": ["Olduvai.sh", "olduvai"],
    "items_opt": [],
    "attr": {
        "title": "Olduvai",
        "porter": [porter],
        "desc": desc,
        "desc_md": None,
        "inst": inst,
        "inst_md": None,
        "genres": ["platformer"],
        "image": None,
        "rtr": False,
        "exp": False,
        "runtime": [],
        "min_glibc": "2.17",
        "reqs": [],
        "arch": json.loads(arch),
    },
}
with open(path, "w", encoding="utf-8") as f:
    json.dump(port, f, indent=4, ensure_ascii=False)
    f.write("\n")
PY

# <name> is the engine's, never the game's (owner, 2026-09-14); <developer>
# is ours: naming the original's would say they made this port.
cat > "${OUT_ABS}/gameinfo.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<gameList>
  <game>
    <path>./Olduvai.sh</path>
    <name>Olduvai</name>
    <desc>${DESC}</desc>
    <releasedate>19910101T000000</releasedate>
    <developer>${PORTER}</developer>
    <genre>Platform</genre>
    <image>./olduvai/screenshot.png</image>
  </game>
</gameList>
XML

cat > "${OUT_ABS}/README.md" <<'MD'
