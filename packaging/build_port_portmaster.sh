echo "PortMaster package ($(IFS=' '; echo "${ARCHES[*]}")) written to ${OUT_ABS}"
(cd "${OUT_ABS}" && find . -type f | sed 's|^\./||' | sort) |
    while IFS= read -r f; do
        printf '  %10s  %s\n' "$(wc -c < "${OUT_ABS}/${f}" | tr -d ' ')" "${f}"
    done

# ── the zip PortMaster installs ─────────────────────────────────────────────
# The directory above is PortMaster-New's repository layout (store files beside
# the launcher).  Its INSTALLER (harbourmaster) wants them inside the port
# folder: it merges olduvai/gameinfo.xml into EmulationStation's game list
# (name, description, the screenshot as the launcher image) and keeps
# olduvai/port.json.  Loose at the zip's root they are tolerated, never merged
# and left as clutter in ports/.  So the zip holds Olduvai.sh and olduvai/ only.
if [ -n "${RELEASE_ZIP}" ]; then
    mkdir -p "$(dirname "${RELEASE_ZIP}")"
    ZIP_ABS="$(cd "$(dirname "${RELEASE_ZIP}")" && pwd -P)/$(basename "${RELEASE_ZIP}")"
    case "${ZIP_ABS}" in
        "${REPO_ROOT}/"*)
            echo "build_port_portmaster: refusing to write a zip inside the repo." >&2
            exit 1 ;;
    esac
    python3 - "${OUT_ABS}" "${ZIP_ABS}" <<'PY'
import os, sys, zipfile
src, dst = sys.argv[1], sys.argv[2]
INSIDE = ("port.json", "gameinfo.xml", "README.md")   # root -> olduvai/
if os.path.exists(dst):
    os.remove(dst)
with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
    def put(path, arc):
        info = zipfile.ZipInfo(arc, date_time=(2026, 1, 1, 0, 0, 0))
        mode = 0o755 if os.access(path, os.X_OK) or arc.endswith(".sh") else 0o644
        info.external_attr = (0o100000 | mode) << 16
        info.compress_type = zipfile.ZIP_DEFLATED
        with open(path, "rb") as f:
            z.writestr(info, f.read())
    put(os.path.join(src, "Olduvai.sh"), "Olduvai.sh")
    for root, _dirs, files in sorted(os.walk(os.path.join(src, "olduvai"))):
        for name in sorted(files):
            path = os.path.join(root, name)
            put(path, os.path.relpath(path, src).replace(os.sep, "/"))
    for name in INSIDE:
        put(os.path.join(src, name), "olduvai/" + name)
PY
    echo "PortMaster release zip written to ${ZIP_ABS} ($(wc -c < "${ZIP_ABS}" | tr -d ' ') bytes)"
fi
